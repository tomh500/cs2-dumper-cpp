std::string identifier(const std::string& name) {
    std::string out;
    for(unsigned char c:name) out+=((c>='a'&&c<='z') || (c>='A'&&c<='Z') || (c>='0'&&c<='9') || c=='_') ? static_cast<char>(c) : '_';
    if(out.empty() || (out.front()>='0' && out.front()<='9')) out="id_"+out;
    static const std::set<std::string> reserved={
        "align","allowzero","and","anyframe","anytype","as","asm","async","await","become","bool","box","break","byte",
        "case","catch","char","class","comptime","concept","const","constexpr","consteval","constinit","continue","crate",
        "decltype","default","defer","delegate","delete","do","double","dyn","else","enum","errdefer","error","event",
        "explicit","export","extern","false","final","fixed","float","fn","for","friend","goto","if","impl","implicit",
        "in","inline","int","interface","internal","is","let","lock","long","loop","match","mod","move","mutable",
        "namespace","new","noalias","noinline","nosuspend","null","nullptr","object","opaque","operator","or","orelse",
        "out","override","packed","params","priv","private","protected","pub","public","readonly","ref","register",
        "reinterpret_cast","requires","resume","return","sbyte","sealed","self","Self","short","signed","sizeof","static",
        "static_assert","static_cast","string","struct","super","suspend","switch","test","this","thread_local","threadlocal",
        "throw","trait","true","try","type","typedef","typeid","typename","typeof","u8","u16","u32","u64","uint","ulong",
        "unchecked","union","unreachable","unsafe","unsized","unsigned","use","using","var","virtual","void","volatile",
        "wchar_t","where","while","with","yield"};
    if(reserved.count(out) || out.rfind("__",0)==0 || (out.size()>1 && out[0]=='_' && std::isupper(static_cast<unsigned char>(out[1])))) out="id_"+out;
    return out;
}
